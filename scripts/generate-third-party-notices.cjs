const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const packageJson = JSON.parse(fs.readFileSync(path.join(root, "package.json"), "utf8"));
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const packages = Object.keys(packageJson.dependencies).sort((a, b) => a.localeCompare(b)).map((name) => {
  const lockEntry = lock.packages?.[`node_modules/${name}`] ?? {};
  const packageRoot = path.join(root, "node_modules", ...name.split("/"));
  let installed = {};
  try { installed = JSON.parse(fs.readFileSync(path.join(packageRoot, "package.json"), "utf8")); } catch { /* Report missing metadata below. */ }
  const filenames = fs.existsSync(packageRoot)
    ? fs.readdirSync(packageRoot).filter((file) => /^(licen[cs]e|copying|notice)(?:\..*)?$/i.test(file)).sort()
    : [];
  const noticeParts = filenames.map((file) => {
    const body = fs.readFileSync(path.join(packageRoot, file), "utf8").replace(/\r\n/g, "\n").trim();
    return body ? `--- ${file} ---\n${body}` : "";
  }).filter(Boolean);
  const noticeText = noticeParts.join("\n\n") || "O pacote não forneceu um arquivo LICENSE/NOTICE na instalação auditada; consulte os metadados e o repositório do pacote antes da distribuição.";
  const copyright = [...new Set(noticeText.split("\n").filter((line) => /copyright|©/i.test(line)).map((line) => line.trim()))].slice(0, 4);
  return {
    name,
    version: lockEntry.version ?? installed.version ?? "desconhecida",
    license: lockEntry.license ?? installed.license ?? "não identificada",
    repository: repositoryUrl(installed.repository),
    noticeText,
    copyright,
  };
});

const grouped = new Map();
for (const item of packages) {
  const digest = crypto.createHash("sha256").update(item.noticeText).digest("hex").slice(0, 12);
  const id = `${slug(item.license)}-${digest}`;
  const group = grouped.get(id) ?? { id, license: item.license, packages: [], text: item.noticeText };
  group.packages.push(`${item.name}@${item.version}`);
  grouped.set(id, group);
  item.groupId = id;
}
const groups = [...grouped.values()].sort((a, b) => a.license.localeCompare(b.license) || a.id.localeCompare(b.id));

const markdown = [
  "# Third-Party Notices",
  "",
  "> Gerado por `node scripts/generate-third-party-notices.cjs` a partir das dependências diretas de runtime instaladas.",
  "> Este inventário é técnico e inicial. Dependências transitivas, artefatos nativos e obrigações de distribuição ainda exigem revisão antes de uma publicação comercial.",
  "",
  "## Inventário",
  "",
  "| Pacote | Versão | Licença declarada | Copyright identificado | Repositório |",
  "| --- | --- | --- | --- | --- |",
  ...packages.map((item) => `| ${escapeCell(item.name)} | ${escapeCell(item.version)} | ${escapeCell(item.license)} | ${item.copyright.length ? escapeCell(item.copyright.join("; ")) : "não destacado no arquivo"} | ${item.repository ? `[origem](${item.repository})` : "não informado"} |`),
  "",
  "## Textos e avisos agrupados",
  "",
  ...groups.flatMap((group) => [
    `### ${group.license} — ${group.packages.join(", ")}`,
    "",
    "```text",
    group.text.replace(/```/g, "` ` `"),
    "```",
    "",
  ]),
].join("\n").replace(/\n+$/, "\n");

const generated = `// Generated by scripts/generate-third-party-notices.cjs. Do not edit manually.\n` +
  `export interface ThirdPartyPackageNotice { name: string; version: string; license: string; repository: string | null; copyright: string[]; groupId: string }\n` +
  `export interface ThirdPartyNoticeGroup { id: string; license: string; packages: string[]; text: string }\n` +
  `export const thirdPartyPackages: ThirdPartyPackageNotice[] = ${JSON.stringify(packages.map(({ noticeText: _noticeText, ...item }) => item), null, 2)};\n` +
  `export const thirdPartyNoticeGroups: ThirdPartyNoticeGroup[] = ${JSON.stringify(groups, null, 2)};\n`;

writeOrCheck(path.join(root, "THIRD_PARTY_NOTICES.md"), markdown);
writeOrCheck(path.join(root, "src", "legal", "thirdPartyNotices.generated.ts"), generated);

function writeOrCheck(target, contents) {
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (current.replace(/\r\n/g, "\n") !== contents) {
      console.error(`${path.relative(root, target)} está desatualizado. Execute npm run legal:notices.`);
      process.exitCode = 1;
    }
    return;
  }
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, contents, "utf8");
  console.log(`Gerado: ${path.relative(root, target)}`);
}

function repositoryUrl(repository) {
  const raw = typeof repository === "string" ? repository : repository?.url;
  if (!raw) return null;
  return raw.replace(/^git\+/, "").replace(/\.git$/, "");
}
function slug(value) { return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "unknown"; }
function escapeCell(value) { return String(value).replace(/\|/g, "\\|").replace(/\r?\n/g, " "); }
