const assert = require('node:assert/strict');
const load = require('./community-test-loader.cjs')();
const { createProfile, validateProfile, canView, goalProgress } = load('src/community/domain/profile');
const { calculateStats, currentStreak } = load('src/community/domain/metrics');
const { applyReadingEvents, progression, achievements, activityText } = load('src/community/domain/progression');
const identity = { userId: 'owner', username: 'leitor', displayName: 'Leitor', avatar: null };
const profile = createProfile(identity, 1);
assert.equal(profile.privacy, 'PRIVATE');
assert.throws(() => validateProfile({ ...profile, readingGoal: { year: 2026, books: 0 } }));
assert.throws(() => validateProfile({ ...profile, avatar: 'javascript:alert(1)' }));
assert.throws(() => validateProfile({ ...profile, activityPrivacy: 'OPEN' }));
assert.deepEqual(validateProfile({ ...profile, favoriteGenres: ['Filosofia', 'Filosofia'] }).favoriteGenres, ['Filosofia']);
for (const privacy of ['PUBLIC', 'FOLLOWERS', 'PRIVATE']) assert(canView(privacy, 'owner', 'owner'));
assert(canView('PUBLIC', 'owner', null));
assert(!canView('PRIVATE', 'owner', 'other', true));
assert(!canView('FOLLOWERS', 'owner', 'other'));
assert(canView('FOLLOWERS', 'owner', 'other', true));
assert.equal(goalProgress({ year: 2026, books: 10 }, null), null);
assert.deepEqual(goalProgress({ year: 2026, books: 2 }, { 2026: 3 }), { completed: 3, target: 2, fraction: 1 });
const base = { title: 'Obra', author: 'Autor', progress: null, genres: null, startedAt: null, completedAt: null, pagesRead: null, readingSeconds: null };
const books = ['unread', 'reading', 'completed', 'abandoned', 'interrupted'].map((status, i) => ({ ...base, id: String(i), status }));
const snapshot = { books, scope: 'device', userId: null, history: [], readingDays: null };
const stats = calculateStats(snapshot, '2026-10-13');
assert.deepEqual([stats.total, stats.started, stats.unread, stats.reading, stats.completed, stats.abandoned, stats.interrupted], [5,4,1,1,1,1,1]);
for (const field of ['pagesRead','readingSeconds','streak','booksByMonth','booksByYear','mostReadGenres']) assert.equal(stats[field], null);
const dated = calculateStats({ ...snapshot, books: [{ ...books[2], completedAt: new Date(2026, 9, 13, 12).getTime(), genres: ['Filosofia', 'Filosofia'], pagesRead: 12, readingSeconds: 60 }] }, '2026-10-13');
assert.equal(dated.booksByMonth['2026-10'], 1); assert.equal(dated.booksByYear['2026'], 1);
assert.deepEqual(dated.mostReadGenres, [{ genre: 'Filosofia', books: 1 }]);
assert.equal(dated.pagesRead,12); assert.equal(dated.readingSeconds,60);
assert.throws(() => calculateStats({ ...snapshot, books: [books[0],books[0]] }, '2026-10-13'));
assert.equal(currentStreak(['2026-10-12','2026-10-11','2026-10-12'], '2026-10-13'), 2);
assert.equal(currentStreak(['2026-10-10'], '2026-10-13'), 0);
assert.equal(currentStreak(['2026-10-13','2026-10-12','2026-10-14'], '2026-10-13'), 2);
assert.equal(currentStreak(['2026-02-28','2026-03-01'], '2026-03-01'), 2);
let state = { version: 1, userId: 'owner', revision: 0, profile, includeDeviceLibrary: false, awards: [], activities: [] };
const event = { id: 'event', userId: 'owner', type: 'BOOK_STARTED', bookId: 'one', bookTitle: 'O Banquete', completionId: null, streakDay: null, occurredAt: null };
state = applyReadingEvents(state, [event, { ...event, id: 'different-event' }], 2);
assert.equal(progression(state.awards.reduce((n,a) => n+a.points,0)).points, 10);
assert.equal(state.activities.length,1);
const completion = { ...event, type: 'BOOK_COMPLETED' };
state = applyReadingEvents(state, [completion, completion],3);
assert.equal(state.awards.length,2); assert.equal(state.activities.filter(a => a.type === 'level_reached').length,1);
state = applyReadingEvents(state, [{ ...completion, id: 'reopen' }],4); assert.equal(state.awards.length,2);
state = applyReadingEvents(state, [{ ...completion, completionId: 'trusted-reread-2' }],5); assert.equal(state.awards.length,3);
assert.throws(() => applyReadingEvents(state, [{ ...event, userId: 'other' }],6));
assert.throws(() => applyReadingEvents(state, [{ ...event, type: 'READING_STREAK' }],6));
assert.equal(achievements(state)[0].unlockedAt,3);
assert.match(activityText(state.activities[0]),/em andamento registrada/);
assert.equal(progression(4000).fraction,1); assert.throws(() => progression(-1));
console.log('PASS community domain: profile, privacy, goals, honest metrics, calendar/streak, progression, semantic idempotence, completion revisions, activity, achievement.');
