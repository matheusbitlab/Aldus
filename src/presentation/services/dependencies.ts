import { GetLibraryUseCase } from "@/src/domain/usecases/GetLibraryUseCase";
import { SeedMockBookUseCase } from "@/src/domain/usecases/SeedMockBookUseCase";
import { SqliteBookRepository } from "@/src/data/repositories/SqliteBookRepository";
import { SqliteChapterRepository } from "@/src/data/repositories/SqliteChapterRepository";
import { SqliteReadingProgressRepository } from "@/src/data/repositories/SqliteReadingProgressRepository";
import { OpenBookUseCase } from "@/src/domain/usecases/OpenBookUseCase";
import { UpdateReadingProgressUseCase } from "@/src/domain/usecases/UpdateReadingProgressUseCase";
import { SqliteBookmarkRepository } from "@/src/data/repositories/SqliteBookmarkRepository";
import { SqliteHighlightRepository } from "@/src/data/repositories/SqliteHighlightRepository";
import { EpubParserService } from "@/src/data/epub/EpubParserService";
import { EpubFileImporter } from "@/src/data/epub/EpubFileImporter";
import { ImportEpubUseCase } from "@/src/domain/usecases/ImportEpubUseCase";
import { SqliteSearchHistoryRepository } from "@/src/data/repositories/SqliteSearchHistoryRepository";
import { NetworkFetcherService } from "@/src/data/scraping/NetworkFetcherService";
import { RobotsCacheService } from "@/src/data/scraping/RobotsCacheService";
import { ThrottleQueue } from "@/src/data/scraping/ThrottleQueue";
import { LinkValidatorService } from "@/src/data/scraping/LinkValidatorService";
import { GutenbergSearchPlugin } from "@/src/data/scraping/GutenbergSearchPlugin";
import { SearchBooksUseCase } from "@/src/domain/usecases/SearchBooksUseCase";
import { DownloadManager } from "@/src/data/downloads/DownloadManager";

const bookRepository = new SqliteBookRepository();
const chapterRepository = new SqliteChapterRepository();
const readingProgressRepository = new SqliteReadingProgressRepository();
const importEpub = new ImportEpubUseCase(new EpubParserService(), bookRepository, chapterRepository);
const networkFetcher = new NetworkFetcherService();
const searchHistoryRepository = new SqliteSearchHistoryRepository();
const searchBooks = new SearchBooksUseCase([new GutenbergSearchPlugin()], networkFetcher, new RobotsCacheService(networkFetcher), new ThrottleQueue(), new LinkValidatorService(networkFetcher), searchHistoryRepository);
const downloadManager = new DownloadManager(new EpubFileImporter(importEpub));
export const appDependencies = { bookRepository, chapterRepository, readingProgressRepository, bookmarkRepository: new SqliteBookmarkRepository(), highlightRepository: new SqliteHighlightRepository(), getLibrary: new GetLibraryUseCase(bookRepository), seedMockBook: new SeedMockBookUseCase(bookRepository, chapterRepository, readingProgressRepository), openBook: new OpenBookUseCase(bookRepository, chapterRepository, readingProgressRepository), updateReadingProgress: new UpdateReadingProgressUseCase(readingProgressRepository), epubImporter: new EpubFileImporter(importEpub), searchBooks, downloadManager };
